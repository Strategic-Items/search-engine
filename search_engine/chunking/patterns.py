    r"^\s*[\[〔【<〈]\s*[^\]〕】>〉]{0,12}?(?:별\s*표|별\s*지|서\s*식|부\s*록)[^\]〕】>〉]{0,30}[\]〕】>〉]\s*$"
    # 둥근 괄호는 줄 전체가 부록 번호 표지뿐일 때만("(별지 제1호 서식)", "(별표 2의3)") -- "(별표 1 참조)"는 본문 참조다
