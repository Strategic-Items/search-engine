# 괄호로 둘러싼 한 줄 제목: "[ 주요 개정내용 ]", "【 개정된 관리업무 분류 】", "< 참고 : 부칙조항 >".
BRACKET_TITLE = re.compile(r"^\s*[\[【〔<〈《]\s*[^\]】〕>〉》\n]{2,40}?\s*[\]】〕>〉》]\s*$")
