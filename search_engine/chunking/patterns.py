    ("검은원문자", re.compile(r"^\s*[➊-➓❶-❿]")),
    ("네모", re.compile(r"^\s*[□☐\u20de]")),
    ("동그라미", re.compile(r"^\s*([○]|[ㅇo](?=\s|[(（]))")),
    ("작은동그라미", re.compile(r"^\s*[◦∘]")),
