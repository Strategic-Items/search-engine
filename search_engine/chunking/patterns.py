# 표지 뒤에 영문 번역 같은 짧은 꼬리가 같은 줄에 붙은 별표·별지 표지: "[별지 제2호의2 서식] Annexed paper No. 2-2".
# 앞 대괄호 표지만 잡는다 -- 꼬리가 짧고 문장이 아닌지는 `annex_label_head()`가 본다.
# 국가법령정보센터 별표 파일의 머리 줄은 `■ 법령명` 뒤에 표지가 온다: "■ 대외무역법 시행령 [별표 2] <개정 2014.1.28>".
# 앞머리 법령명은 `■`로 시작할 때만 받는다 -- 본문 "자세한 내용은 [별표 1] …"을 표지로 보지 않게.
ANNEX_LABEL_HEAD = re.compile(
    r"^\s*(?:■\s*[^\[\]\n]{1,80}?\s*)?[\[〔【<〈]\s*[^\]〕】>〉]{0,12}?(?:별\s*표|별\s*지|서\s*식|부\s*록)[^\]〕】>〉]{0,30}[\]〕】>〉]")
_LABEL_NOTE_TAIL = re.compile(r"\s*[<〈\[][^>〉\]]*(?:개정|신설|삭제|전문개정)[^>〉\]]*[>〉\]]\s*$")
# 발령 문서의 머리 줄(그 번호만 있는 한 줄): "산업통상부고시 제 2026-101 호", "국방부훈령 제3031호". 개정고시안처럼
# 앞에 개정 이유·요약 목록이 있는 문서에서 실제 본문이 시작하는 경계다(앞 목록이 여기서 닫혀야 한다).
ISSUANCE_LINE = re.compile(
    r"^\s*(?:[◉●○◎■□◆◇▶▷※ㅇ]\s*)?(?:\S{0,20}?\s?)?(?:훈령|대통령령|법률|총리령|부령|고시|규칙|예규)\s*제\s*\d{1,4}"
    r"(?:\s*[-‐–—]\s*\d+)?\s*호\s*$")  # 앞 기호(`◉ 산업통상자원부고시 제2021-202호`)와 기관명·종류 사이 띄어쓰기 허용


def issuance_label(text: str) -> str | None:
    """발령 머리 줄이면 경로에 쓸 글자(앞 기호를 뗀 것), 아니면 None."""
    first = (text or "").strip().split("\n", 1)[0].strip()
    if not ISSUANCE_LINE.match(first):
        return None
    return " ".join(first.lstrip("◉●○◎■□◆◇▶▷※ㅇ").split())
# 개정 지시문: "제20조제1항제4호를 제3호로 하고, …한다.", "별표 22 제2호를 다음과 같이 한다.", "별지 제3호서식을 삭제한다."
# 개정고시 본문에서 앞에 실은 신설 조문(`제18조의3(…)`)의 내용이 아니라 고시 본문의 다음 지시다 -- 조문 경로를 닫는다.
# 시작이 조문 인용 + 위치(제N항·제N호·중·를) 또는 별표·별지이고, 끝이 개정 동사여야 한다(본문 "제5조에 따른 …"과 가른다).
AMENDMENT_INSTRUCTION = re.compile(
    r"^\s*(?:제\s*\d+\s*(?:장|절)\s*)?(?:제\s*\d+\s*조(?:\s*의\s*\d+)?\s*(?:제\s*\d+\s*[항호]|중|[을를]|각\s*호|의\s*제목)"
    r"|별\s*표\s*\d+|별\s*지\s*제\s*\d+)"
    r"[\s\S]*(?:(?:신설|삭제|개정)한다|(?:으로|로)\s*한다|같이\s*한다)\s*[.。]?\s*$")
# 다른 법령을 고치는 조문(`제4조(다른 법률의 개정)`): 조문 내용 자체가 개정 지시문이라 지시문이 나와도 이 조문은 닫지 않는다.
AMENDING_ARTICLE = re.compile(r"[(（][^)）]*개정[^)）]*[)）]")


def closes_article(title: str) -> bool:
    """개정 지시문이 나왔을 때 닫을 조문인가: 조문 제목이고, 표제가 다른 법령의 개정이 아니다."""
    return bool(re.match(r"^\s*제\s*\d+\s*조", title or "")) and not AMENDING_ARTICLE.search(title or "")
# 날짜만 있는 줄(서명란·표지 날짜) -- 제목이 아니다.
DATE_ONLY = re.compile(r"^\s*(?:19|20)\d{2}\s*[.년]\s*\d{1,2}\s*[.월]?\s*(?:\d{1,2}\s*[.일]?)?\s*$")
# 접두 코드로 계층을 나타내는 줄(통제번호·품목번호): "1A 시스템…", "1A001 불소화합물…", "1A001.a 항공기…", "ML1.a …".
# 숫자와 대문자가 모두 든 토큰 하나로 시작한다. 계층은 코드의 접두 관계로 정한다(`hwpstruct.elements._code_parents`).
CODE_LINE = re.compile(r"^\s*(?P<code>(?=[0-9A-Z]*\d)(?=[0-9A-Z]*[A-Z])[0-9A-Z]{2,8}(?:\.[0-9a-z]{1,4})*)\s+\S")
# 표·그림 캡션("<표 1> …", "[그림 3] …") -- 제목이 아니라 바로 뒤 표·그림의 이름이다.
CAPTION = re.compile(r"^\s*[<〈\[(（【]?\s*(?:표|그림|도표|사진|차트)\s*[\d０-９]+")
# 목차 줄: 끝에 쪽 번호("1. 국제수출통제체제의 최근동향 4", "총칙 ······ 12").
TOC_LINE = re.compile(r"(?:\s|[.·…]{2,})\d{1,3}\s*$")
_ANNEX_TAIL_MAX_CHARS = 40
_SENTENCE_TAIL = re.compile(r"(?:다|요|음|함)\s*[.。]?\s*$")


def annex_label_head(text: str) -> str | None:
    """줄 첫머리의 별표·별지 표지와 같은 줄의 짧은 꼬리(별표 제목·영문 번역): `[별표 3] 물품별 적정 원산지표시 방법(제9조제1항 관련)`,
    `[별지 제2호의2 서식] Annexed paper No. 2-2`. 꼬리는 짧고 문장이 아니어야 한다 -- 표지 뒤에 본문 문장이 이어지면 표지 줄이 아니다.
    꼬리까지 돌려주는 것은 경로(heading_path)에 별표 제목이 남게 하려는 것이다(`[별표 3]`만 남으면 무슨 별표인지 모른다)."""
    first = (text or "").strip().split("\n", 1)[0].strip()
    if ANNEX_LABEL.match(first):
        return " ".join(first.split())
    m = ANNEX_LABEL_HEAD.match(first)
    if not m:
        return None
    tail = first[m.end():].strip()
    if len(tail) > _ANNEX_TAIL_MAX_CHARS or _SENTENCE_TAIL.search(tail):
        return None
    # 경로에 쓸 표지: 앞 `■`와 끝 연혁 주석(`<개정 2014.1.28>`)은 뗀다 -- "대외무역법 시행령 [별표 2]"
    label = _LABEL_NOTE_TAIL.sub("", first).strip().lstrip("■").strip()
    return " ".join(label.split())


def part_boundary_line(text: str) -> bool:
    """본문을 새로 여는 한 줄: 별표·별지 표지, 발령 문서 머리 줄, 신·구조문 대비표 제목. 앞에서 열린 목록·조문이 여기서 닫힌다."""
    first = (text or "").strip().split("\n", 1)[0].strip()
    return bool(annex_label_head(first) or ISSUANCE_LINE.match(first)
                or (len(first) <= 20 and COMPARISON_TABLE.search(first)))

BULLET_CLASS = {
    **{c: "bullet" for c in "ㅇ○●◦•·∙▪◆◇▶▷"},
    **{c: "dash" for c in "-–—"},
    **{c: "note" for c in "※*"},
    **{c: "checkbox" for c in "□☐"},
}


def configure(**overrides) -> None:
    """이 모듈의 패턴 상수를 이름으로 덮어쓴다. 모르는 이름이면 오타를 막으려고 예외를 낸다."""
    for name, value in overrides.items():
        if name not in globals() or name.startswith("_") or name == "configure":
            raise KeyError(f"알 수 없는 패턴 이름: {name}")
        globals()[name] = value
