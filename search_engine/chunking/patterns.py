# ---- 법령·고시 문서의 구조 제목(번호 없이 쓰는 것). HWP·PDF 공통 판정에 쓴다(`hwpstruct.elements`).
# 부칙: "부 칙", "부칙 <제정 2004. 10. 20>", "부 칙 <5차개정, 2008. 1. 1 >" -- 본칙의 장·조와 같은 단계의 구분이다.
SUPPLEMENTARY = re.compile(r"^\s*부\s*칙\s*(?:[<〈(（\[][^>〉)）\]]*[>〉)）\]]\s*)?$")
# 별표·별지·서식 표지: "[별표 1]", "[별지 제13호 서식]", "[ 공고 별지 제4호 서식 ]", "〔별표 2〕", "<별표 2호의3>".
# 둥근 괄호는 받지 않는다 -- "(별표 1 참조)"는 본문 속 참조다.
